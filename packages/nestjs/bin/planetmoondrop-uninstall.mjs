#!/usr/bin/env node
/**
 * planetmoondrop-uninstall — interactive teardown for @planetmoondrop/centralized-logger
 *
 * Usage:
 *   npx -p @planetmoondrop/centralized-logger planetmoondrop uninstall
 *   npx planetmoondrop uninstall               (after installing the package in your project)
 *
 * What it does (mirror image of `planetmoondrop init`):
 *   1. Removes the LokiLoggerModule.register({...}) block + its import from app.module.ts,
 *      ONLY if it matches what init would have generated (skips registerAsync or anything
 *      that looks hand-edited beyond recognition).
 *   2. Removes the "import './planetmoondrop/tracing'" first line from main.ts.
 *   3. Deletes the generated src/planetmoondrop/tracing.ts file (only if it still matches
 *      the generated header — skips if the user edited it).
 *   4. Uninstalls the OTEL SDK packages (if present).
 *   5. Uninstalls @planetmoondrop/centralized-logger, winston, uuid from the project
 *      (asks for confirmation, since winston/uuid may be used elsewhere in the codebase).
 *
 * This script is intentionally conservative: anything it's not sure about, it leaves alone
 * and tells you to remove by hand.
 */

import {
  existsSync,
  readFileSync,
  writeFileSync,
  unlinkSync,
  rmdirSync,
  readdirSync,
} from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, join, dirname } from 'node:path';
import { createRequire } from 'node:module';

// ─── Colours (no extra deps) ──────────────────────────────────────────────────
const c = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  cyan: '\x1b[36m',
  red: '\x1b[31m',
  gray: '\x1b[90m',
};

const ok = (msg) => console.log(`  ${c.green}✔${c.reset}  ${msg}`);
const skip = (msg) => console.log(`  ${c.gray}–${c.reset}  ${c.dim}${msg}${c.reset}`);
const info = (msg) => console.log(`  ${c.cyan}i${c.reset}  ${msg}`);
const warn = (msg) => console.log(`  ${c.yellow}!${c.reset}  ${msg}`);
const err = (msg) => console.log(`  ${c.red}✖${c.reset}  ${msg}`);
const br = () => console.log('');

// ─── Load prompts (bundled as dep of @planetmoondrop/centralized-logger) ─────────────
const _require = createRequire(import.meta.url);
let prompts;
try {
  prompts = _require('prompts').default ?? _require('prompts');
} catch {
  err('Could not load the `prompts` package. Try: npm install @planetmoondrop/centralized-logger');
  process.exit(1);
}

// ─── Package manager detection (same logic as init) ──────────────────────────
function detectPackageManager(cwd) {
  let dir = cwd;
  for (let i = 0; i < 8 && dir; i++) {
    if (existsSync(join(dir, 'pnpm-lock.yaml'))) return 'pnpm';
    if (existsSync(join(dir, 'yarn.lock'))) return 'yarn';
    if (existsSync(join(dir, 'bun.lockb'))) return 'bun';
    const parent = resolve(dir, '..');
    if (parent === dir) break;
    dir = parent;
  }
  return 'npm';
}

function uninstallCmd(pm, packages) {
  const pkgList = packages.join(' ');
  switch (pm) {
    case 'pnpm':
      return `pnpm remove ${pkgList}`;
    case 'yarn':
      return `yarn remove ${pkgList}`;
    case 'bun':
      return `bun remove ${pkgList}`;
    default:
      return `npm uninstall ${pkgList}`;
  }
}

// ─── Same package lists as init ───────────────────────────────────────────────
const CORE_PACKAGES = ['@planetmoondrop/centralized-logger', 'winston', 'uuid'];
const OTEL_PACKAGES = [
  '@opentelemetry/sdk-node',
  '@opentelemetry/exporter-trace-otlp-http',
  '@opentelemetry/auto-instrumentations-node',
  '@opentelemetry/resources',
  '@opentelemetry/semantic-conventions',
];

function readPackageJson(cwd) {
  try {
    return JSON.parse(readFileSync(join(cwd, 'package.json'), 'utf8'));
  } catch {
    return {};
  }
}

function projectDeclaresDep(pkgJson, name) {
  return Boolean(
    pkgJson.dependencies?.[name] ||
    pkgJson.devDependencies?.[name] ||
    pkgJson.optionalDependencies?.[name],
  );
}

// ─── main.ts unpatcher (reverses TRACING_IMPORT insertion from init) ─────────
const TRACING_IMPORT_LINE_RE =
  /^\s*import\s+['"]\.\/(?:planetmoondrop|moondrop)\/tracing['"];[^\n]*\n/;

/** @returns {'removed' | 'not-found'} */
function unpatchMainTs(mainTsPath) {
  const original = readFileSync(mainTsPath, 'utf8');
  if (!TRACING_IMPORT_LINE_RE.test(original)) {
    return 'not-found';
  }
  const updated = original.replace(TRACING_IMPORT_LINE_RE, '');
  writeFileSync(mainTsPath, updated, 'utf8');
  return 'removed';
}

// ─── tracing.ts remover ───────────────────────────────────────────────────────
// Only delete the file if it still has the generated-file header init wrote,
// so we don't blow away something the user has since hand-edited into
// containing custom logic.
const GENERATED_HEADER_MARKER = 'generated by @planetmoondrop/centralized-logger';

/** @returns {'removed' | 'not-found' | 'modified-skipped'} */
function removeTracingTs(tracingPath) {
  if (!existsSync(tracingPath)) return 'not-found';
  const content = readFileSync(tracingPath, 'utf8');
  if (!content.includes(GENERATED_HEADER_MARKER)) {
    return 'modified-skipped';
  }
  unlinkSync(tracingPath);
  // Clean up the now-empty planetmoondrop/ directory, but only if it's empty.
  const dir = dirname(tracingPath);
  try {
    if (readdirSync(dir).length === 0) {
      rmdirSync(dir);
    }
  } catch {
    // non-fatal — leave the directory if it's not empty or can't be removed
  }
  return 'removed';
}

// ─── app.module.ts unpatcher (reverses patchAppModuleTs from init) ───────────
const LOKI_MODULE_IMPORT_RE =
  /^\s*import\s+\{\s*LokiLoggerModule\s*\}\s+from\s+['"]@planetmoondrop\/centralized-logger['"];?\s*\n/m;

// Matches a single `LokiLoggerModule.register({ ... }),` block as inserted by
// init's buildLokiRegisterBlock — non-greedy across the balanced-ish braces it
// always generates (serviceName / lokiHost / enableMetrics / optional enableTracing).
const LOKI_REGISTER_BLOCK_RE = /\n?[ \t]*LokiLoggerModule\.register\(\{[\s\S]*?\}\),?\n?/;

/** @returns {{ status: 'removed' } | { status: string }} */
function unpatchAppModuleTs(appModulePath) {
  if (!existsSync(appModulePath)) {
    return { status: 'missing-file' };
  }

  let content = readFileSync(appModulePath, 'utf8');

  if (/LokiLoggerModule\.registerAsync\s*\(/.test(content)) {
    return { status: 'is-async' };
  }

  if (!LOKI_REGISTER_BLOCK_RE.test(content)) {
    return { status: 'not-found' };
  }

  content = content.replace(LOKI_REGISTER_BLOCK_RE, '\n');
  content = content.replace(LOKI_MODULE_IMPORT_RE, '');

  writeFileSync(appModulePath, content, 'utf8');
  return { status: 'removed' };
}

// ─── Wizard ───────────────────────────────────────────────────────────────────
async function main() {
  const cwd = process.cwd();

  console.log('');
  console.log(`  ${c.bold}${c.cyan}Planetmoondrop Observability Teardown${c.reset}`);
  console.log(
    `  ${c.dim}@planetmoondrop/centralized-logger — interactive uninstall wizard${c.reset}`,
  );
  br();

  if (!existsSync(join(cwd, 'package.json'))) {
    err('No package.json found in the current directory.');
    info('Run this wizard from the root of your NestJS project.');
    process.exit(1);
  }

  const pm = detectPackageManager(cwd);
  info(`Detected package manager: ${c.bold}${pm}${c.reset}`);
  br();

  const answers = await prompts(
    [
      {
        type: 'text',
        name: 'mainTs',
        message: 'Path to your main.ts (relative to project root):',
        initial: 'src/main.ts',
      },
      {
        type: 'text',
        name: 'appModuleTs',
        message: 'Path to your app.module.ts (relative to project root):',
        initial: 'src/app.module.ts',
      },
      {
        type: 'confirm',
        name: 'removePackages',
        message:
          'Also uninstall the npm packages (@planetmoondrop/centralized-logger, winston, uuid, OTEL SDK)?',
        initial: true,
      },
    ],
    {
      onCancel: () => {
        br();
        warn('Uninstall cancelled.');
        process.exit(0);
      },
    },
  );

  br();

  const mainTsRel = answers.mainTs ?? 'src/main.ts';
  const mainTsPath = resolve(cwd, mainTsRel);
  const appModuleRel = answers.appModuleTs ?? 'src/app.module.ts';
  const appModulePath = resolve(cwd, appModuleRel);
  const tracingPath = join(mainTsPath, '..', 'planetmoondrop', 'tracing.ts');

  // ── Step 1: Unpatch app.module.ts ─────────────────────────────────────────
  const appResult = unpatchAppModuleTs(appModulePath);
  switch (appResult.status) {
    case 'removed':
      ok(`Removed LokiLoggerModule.register() block and import from ${appModuleRel}`);
      break;
    case 'missing-file':
      skip(`${appModuleRel} not found — nothing to unpatch`);
      break;
    case 'is-async':
      warn(`${appModuleRel} uses LokiLoggerModule.registerAsync() — remove this entry manually`);
      break;
    case 'not-found':
      skip(`No LokiLoggerModule.register() block found in ${appModuleRel}`);
      break;
  }

  // ── Step 2: Unpatch main.ts ────────────────────────────────────────────────
  if (!existsSync(mainTsPath)) {
    skip(`${mainTsRel} not found — nothing to unpatch`);
  } else {
    const mainResult = unpatchMainTs(mainTsPath);
    if (mainResult === 'removed') {
      ok(`Removed tracing import line from ${mainTsRel}`);
    } else {
      skip(`No tracing import found in ${mainTsRel} — nothing to remove`);
    }
  }

  // ── Step 3: Remove generated tracing.ts ───────────────────────────────────
  const tracingRelDisplay = tracingPath.replace(cwd, '').replace(/\\/g, '/');
  const tracingResult = removeTracingTs(tracingPath);
  switch (tracingResult) {
    case 'removed':
      ok(`Deleted ${tracingRelDisplay}`);
      break;
    case 'not-found':
      skip(`${tracingRelDisplay} not found — nothing to delete`);
      break;
    case 'modified-skipped':
      warn(
        `${tracingRelDisplay} looks hand-edited — left in place, remove manually if no longer needed`,
      );
      break;
  }

  br();

  // ── Step 4 & 5: Uninstall packages ────────────────────────────────────────
  if (!answers.removePackages) {
    skip('Package removal skipped by request — packages left installed');
  } else {
    const pkgJson = readPackageJson(cwd);

    const otelToRemove = OTEL_PACKAGES.filter((p) => projectDeclaresDep(pkgJson, p));
    if (otelToRemove.length > 0) {
      const cmd = uninstallCmd(pm, otelToRemove);
      info('Removing OpenTelemetry packages...');
      info(`  ${c.dim}${cmd}${c.reset}`);
      br();
      try {
        execSync(cmd, { cwd, stdio: 'inherit' });
        br();
        ok('OpenTelemetry packages removed');
      } catch {
        err('Package removal failed. Run the command above manually.');
      }
    } else {
      skip('No OpenTelemetry packages found in package.json — skipping');
    }

    const coreToRemove = CORE_PACKAGES.filter((p) => projectDeclaresDep(pkgJson, p));
    if (coreToRemove.length > 0) {
      warn(
        'winston and uuid may be used elsewhere in your codebase beyond this logger — double-check before removing.',
      );
      const { confirmCore } = await prompts({
        type: 'confirm',
        name: 'confirmCore',
        message: `Remove ${coreToRemove.join(', ')}?`,
        initial: false,
      });

      if (confirmCore) {
        const cmd = uninstallCmd(pm, coreToRemove);
        info('Removing core logging packages...');
        info(`  ${c.dim}${cmd}${c.reset}`);
        br();
        try {
          execSync(cmd, { cwd, stdio: 'inherit' });
          br();
          ok('Core logging packages removed');
        } catch {
          err('Package removal failed. Run the command above manually.');
        }
      } else {
        skip('Core package removal declined — left installed');
      }
    } else {
      skip('No core logging packages found in package.json — skipping');
    }
  }

  br();
  console.log(`  ${c.bold}${c.green}Teardown complete!${c.reset}`);
  br();
  info('Review the diff before committing — this script is conservative and may leave');
  info('config (env vars, Docker Compose Loki/Tempo services, etc.) for you to remove by hand.');
  br();
}

main().catch((e) => {
  err(String(e));
  process.exit(1);
});
