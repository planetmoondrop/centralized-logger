#!/usr/bin/env node
/**
 * moondrop-init — interactive setup wizard for @moondrop/centralized-logger
 *
 * Usage:
 *   npx -p @moondrop/centralized-logger moondrop init
 *   npx moondrop init               (after installing the package in your project)
 *
 * What it does:
 *   1. Asks which observability features you want.
 *   2. Installs the OTEL SDK packages if tracing is selected.
 *   3. Generates src/moondrop/tracing.ts in your project.
 *   4. Patches src/main.ts so it imports './moondrop/tracing' as the very first line.
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';

// ─── Colours (no extra deps) ──────────────────────────────────────────────────
const c = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  cyan: '\x1b[36m',
  red: '\x1b[31m',
  gray: '\x1b[90m',
};

const ok = (msg) => console.log(`  ${c.green}✔${c.reset}  ${msg}`);
const skip = (msg) => console.log(`  ${c.gray}–${c.reset}  ${c.dim}${msg}${c.reset}`);
const info = (msg) => console.log(`  ${c.cyan}i${c.reset}  ${msg}`);
const warn = (msg) => console.log(`  ${c.yellow}!${c.reset}  ${msg}`);
const err = (msg) => console.log(`  ${c.red}✖${c.reset}  ${msg}`);
const br = () => console.log('');

// ─── Load prompts (bundled as dep of @moondrop/centralized-logger) ─────────────
const _require = createRequire(import.meta.url);
let prompts;
try {
  prompts = _require('prompts').default ?? _require('prompts');
} catch {
  err('Could not load the `prompts` package. Try: npm install @moondrop/centralized-logger');
  process.exit(1);
}

// ─── Package manager detection ────────────────────────────────────────────────
function detectPackageManager(cwd) {
  if (existsSync(join(cwd, 'pnpm-lock.yaml'))) return 'pnpm';
  if (existsSync(join(cwd, 'yarn.lock'))) return 'yarn';
  if (existsSync(join(cwd, 'bun.lockb'))) return 'bun';
  return 'npm';
}

function installCmd(pm, packages) {
  const pkgList = packages.join(' ');
  switch (pm) {
    case 'pnpm':
      return `pnpm add ${pkgList}`;
    case 'yarn':
      return `yarn add ${pkgList}`;
    case 'bun':
      return `bun add ${pkgList}`;
    default:
      return `npm install ${pkgList}`;
  }
}

// ─── OTEL packages required for tracing ──────────────────────────────────────
const OTEL_PACKAGES = [
  '@opentelemetry/sdk-node',
  '@opentelemetry/exporter-trace-otlp-http',
  '@opentelemetry/auto-instrumentations-node',
  '@opentelemetry/resources',
  '@opentelemetry/semantic-conventions',
];

// ─── File generators ──────────────────────────────────────────────────────────
function tracingTsContent(serviceName, otlpEndpoint) {
  return `/**
 * OpenTelemetry initialization — generated by @moondrop/centralized-logger
 *
 * This file MUST be the FIRST import in main.ts. It installs Node.js
 * require-hooks so that http and express are instrumented before NestJS loads.
 *
 * To regenerate: npx -p @moondrop/centralized-logger moondrop init
 */
import { initObservability } from '@moondrop/centralized-logger';

initObservability({
  serviceName: '${serviceName}',
  otlpEndpoint: process.env['OTEL_EXPORTER_OTLP_ENDPOINT'] ?? '${otlpEndpoint}',
  environment: process.env['NODE_ENV'] ?? 'development',
});
`;
}

// ─── main.ts patcher ──────────────────────────────────────────────────────────
const TRACING_IMPORT = `import './moondrop/tracing'; // MUST be first — installs OTEL hooks before any other module loads`;

function patchMainTs(mainTsPath) {
  const original = readFileSync(mainTsPath, 'utf8');

  if (
    original.includes("import './moondrop/tracing'") ||
    original.includes('import "./moondrop/tracing"')
  ) {
    return false; // already patched
  }

  const patched = TRACING_IMPORT + '\n' + original;
  writeFileSync(mainTsPath, patched, 'utf8');
  return true;
}

// ─── Wizard ───────────────────────────────────────────────────────────────────
async function main() {
  const cwd = process.cwd();

  console.log('');
  console.log(`  ${c.bold}${c.cyan}Moondrop Observability Setup${c.reset}`);
  console.log(`  ${c.dim}@moondrop/centralized-logger — interactive init wizard${c.reset}`);
  br();

  // Sanity check: is there a package.json here?
  if (!existsSync(join(cwd, 'package.json'))) {
    err('No package.json found in the current directory.');
    info('Run this wizard from the root of your NestJS project.');
    process.exit(1);
  }

  const pm = detectPackageManager(cwd);
  info(`Detected package manager: ${c.bold}${pm}${c.reset}`);
  br();

  // ── Questions ───────────────────────────────────────────────────────────────
  const answers = await prompts(
    [
      {
        type: 'text',
        name: 'serviceName',
        message: 'Service name (must match your LokiLoggerModule.register serviceName):',
        initial: (() => {
          try {
            const pkg = JSON.parse(readFileSync(join(cwd, 'package.json'), 'utf8'));
            return pkg.name?.replace(/^@[^/]+\//, '') ?? 'my-service';
          } catch {
            return 'my-service';
          }
        })(),
        validate: (v) => v.trim().length > 0 || 'Service name is required',
      },
      {
        type: 'multiselect',
        name: 'features',
        message: 'Select features to enable (space to toggle, enter to confirm):',
        hint: '- Space to select, Enter to confirm',
        instructions: false,
        choices: [
          {
            title: `${c.green}Core Logging${c.reset}  — Loki push, structured JSON, trace context`,
            value: 'logging',
            selected: true,
            disabled: true, // always on
          },
          {
            title: `${c.green}Metrics${c.reset}       — Prometheus /metrics, Node.js system health`,
            value: 'metrics',
            selected: true,
            disabled: true, // always on (prom-client is a direct dep)
          },
          {
            title: `${c.cyan}Tracing${c.reset}       — OpenTelemetry → Tempo waterfall, span correlation`,
            value: 'tracing',
            selected: false,
          },
        ],
      },
      {
        type: 'text',
        name: 'lokiHost',
        message: 'Loki host URL:',
        initial: process.env['LOKI_HOST'] ?? 'http://loki:3100',
      },
      {
        type: (_, values) => (values.features?.includes('tracing') ? 'text' : null),
        name: 'otlpEndpoint',
        message: 'Tempo OTLP endpoint:',
        initial: process.env['OTEL_EXPORTER_OTLP_ENDPOINT'] ?? 'http://tempo:4318',
      },
      {
        type: 'text',
        name: 'mainTs',
        message: 'Path to your main.ts (relative to project root):',
        initial: 'src/main.ts',
      },
    ],
    {
      onCancel: () => {
        br();
        warn('Setup cancelled.');
        process.exit(0);
      },
    },
  );

  br();

  const wantsTracing = answers.features?.includes('tracing');
  const serviceName = answers.serviceName.trim();
  const otlpEndpoint = answers.otlpEndpoint ?? 'http://tempo:4318';
  const mainTsRel = answers.mainTs ?? 'src/main.ts';
  const mainTsPath = resolve(cwd, mainTsRel);
  // Place tracing.ts in a moondrop/ subfolder next to main.ts (e.g. src/moondrop/tracing.ts)
  const tracingPath = join(mainTsPath, '..', 'moondrop', 'tracing.ts');

  // ── Step 1: Install OTEL packages ──────────────────────────────────────────
  if (wantsTracing) {
    const cmd = installCmd(pm, OTEL_PACKAGES);
    info(`Installing OpenTelemetry packages...`);
    info(`  ${c.dim}${cmd}${c.reset}`);
    br();
    try {
      execSync(cmd, { cwd, stdio: 'inherit' });
      br();
      ok('OpenTelemetry packages installed');
    } catch {
      err('Package installation failed. Run the command above manually and re-run init.');
      process.exit(1);
    }
  } else {
    skip('Tracing not selected — OTEL SDK packages skipped');
  }

  // ── Step 2: Generate tracing.ts (sibling of main.ts) ─────────────────────
  if (wantsTracing) {
    if (existsSync(tracingPath)) {
      skip(
        `tracing.ts already exists at ${tracingPath.replace(cwd, '').replace(/\\/g, '/')} — not overwritten`,
      );
    } else {
      mkdirSync(join(tracingPath, '..'), { recursive: true });
      writeFileSync(tracingPath, tracingTsContent(serviceName, otlpEndpoint), 'utf8');
      ok(`Generated ${tracingPath.replace(cwd, '').replace(/\\/g, '/')}`);
    }
  } else {
    skip('tracing.ts not needed without tracing');
  }

  // ── Step 3: Patch main.ts ───────────────────────────────────────────────────
  if (wantsTracing) {
    if (!existsSync(mainTsPath)) {
      warn(`${mainTsRel} not found — skipping main.ts patch`);
      info(`Add this as the VERY FIRST line of your main.ts manually:`);
      info(`  ${c.cyan}${TRACING_IMPORT}${c.reset}`);
    } else {
      const patched = patchMainTs(mainTsPath);
      if (patched) {
        ok(`Patched ${mainTsRel} — import './tracing' added as first line`);
      } else {
        skip(`${mainTsRel} already imports './tracing' — no change needed`);
      }
    }
  } else {
    skip('main.ts patch not needed without tracing');
  }

  // ── Step 4: Print LokiLoggerModule config hint ─────────────────────────────
  br();
  console.log(`  ${c.bold}Next step — update your LokiLoggerModule.register() call:${c.reset}`);
  br();
  console.log(`  ${c.dim}LokiLoggerModule.register({${c.reset}`);
  console.log(`  ${c.dim}  serviceName: '${serviceName}',${c.reset}`);
  console.log(`  ${c.dim}  lokiHost: '${answers.lokiHost}',${c.reset}`);
  console.log(`  ${c.dim}  enableMetrics: true,          // Prometheus /metrics${c.reset}`);
  if (wantsTracing) {
    console.log(
      `  ${c.dim}  enableTracing: true,          // use OTEL span context in logs${c.reset}`,
    );
  }
  console.log(`  ${c.dim}})${c.reset}`);
  br();

  console.log(`  ${c.bold}${c.green}Setup complete!${c.reset}`);
  br();

  if (wantsTracing) {
    info(`Rebuild your Docker images to apply the changes:`);
    info(`  ${c.dim}docker compose up --build${c.reset}`);
    br();
  }
}

main().catch((e) => {
  err(String(e));
  process.exit(1);
});
